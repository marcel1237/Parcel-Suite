@Composable
fun SettingsScreen(persistenceService: PersistenceService) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(24.dp)
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        Text("⚙ Settings & Customization", fontSize = 24.sp, fontWeight = FontWeight.Bold)

        Card(modifier = Modifier.fillMaxWidth()) {
            Column(modifier = Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Text("App Color Theme Managers", fontWeight = FontWeight.SemiBold, color = MaterialTheme.colorScheme.primary)
                Text(
                    text = "Select from AtlantaFX equivalent custom dynamic color profiles.",
                    fontSize = 13.sp,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )

                val themes = listOf(
                    Pair("Primer Dark", ThemeType.PRIMER_DARK),
                    Pair("Dracula (Vampire Theme)", ThemeType.DRACULA),
                    Pair("Nord Dark Slate", ThemeType.NORD_DARK),
                    Pair("Cupertino Dark (Apple style)", ThemeType.CUPERTINO_DARK),
                    Pair("Primer Light", ThemeType.PRIMER_LIGHT),
                    Pair("Nord Light", ThemeType.NORD_LIGHT),
                    Pair("Cupertino Light", ThemeType.CUPERTINO_LIGHT)
                )

                themes.forEach { pair: Pair<String, ThemeType> ->
                    val label = pair.first
                    val type = pair.second
                    val isSelected = ThemeManager.currentTheme == type
                    Card(
                        onClick = { 
                            ThemeManager.currentTheme = type
                            persistenceService.saveTheme(type.name)
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("theme_btn_" + type.name.lowercase(Locale.ROOT)),
                        colors = CardDefaults.cardColors(
                            containerColor = if (isSelected) MaterialTheme.colorScheme.primary.copy(alpha = 0.2f) else MaterialTheme.colorScheme.surfaceVariant
                        ),
                        border = BorderStroke(
                            1.dp,
                            if (isSelected) MaterialTheme.colorScheme.primary else Color.Transparent
                        )
                    ) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(14.dp),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(label, fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal)
                            if (isSelected) {
                                Icon(Icons.Default.RadioButtonChecked, null, tint = MaterialTheme.colorScheme.primary)
                            } else {
                                Icon(Icons.Default.RadioButtonUnchecked, null, tint = MaterialTheme.colorScheme.onSurfaceVariant)
                            }
                        }
                    }
                }
            }
        }
    }
}

