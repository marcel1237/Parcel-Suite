@Composable
fun NewProjectWizardScreen(
    initialTemplate: ProjectTemplate?,
    onCancel: () -> Unit,
    onFinish: (String, String, String, String, String) -> Unit
) {
    var step by remember { mutableIntStateOf(0) }
    val stepsList = listOf("Project", "Language", "Build Tool", "Summary")

    // Form states
    var projectName by remember { mutableStateOf(initialTemplate?.name?.replace(" ", "") ?: "MyProject") }
    var group by remember { mutableStateOf("com.example") }
    var artifact by remember { mutableStateOf(initialTemplate?.id ?: "sampleapp") }
    var language by remember { mutableStateOf(if (initialTemplate?.category == "Kotlin") "Kotlin" else "Java") }
    var buildTool by remember { mutableStateOf("Gradle") }

    Row(modifier = Modifier.fillMaxSize()) {
        // Steps indicator left pane (IDE style wizard side bar)
        Column(
            modifier = Modifier
                .width(180.dp)
                .fillMaxHeight()
                .background(MaterialTheme.colorScheme.surface)
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            Text(
                text = "Wizard Steps",
                fontWeight = FontWeight.Bold,
                fontSize = 14.sp,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(bottom = 8.dp)
            )
            stepsList.forEachIndexed { index: Int, label: String ->
                val isActive = step == index
                val isCompleted = step > index
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Box(
                        modifier = Modifier
                            .size(24.dp)
                            .clip(RoundedCornerShape(12.dp))
                            .background(
                                when {
                                    isActive -> MaterialTheme.colorScheme.primary
                                    isCompleted -> Color(0xFF4CAF50)
                                    else -> MaterialTheme.colorScheme.surfaceVariant
                                }
                            ),
                        contentAlignment = Alignment.Center
                    ) {
                        if (isCompleted) {
                            Icon(
                                imageVector = Icons.Default.Check,
                                contentDescription = null,
                                modifier = Modifier.size(12.dp),
                                tint = Color.White
                            )
                        } else {
                            Text(
                                text = (index + 1).toString(),
                                fontSize = 11.sp,
                                fontWeight = FontWeight.Bold,
                                color = if (isActive) MaterialTheme.colorScheme.onPrimary else MaterialTheme.colorScheme.onSurfaceVariant
