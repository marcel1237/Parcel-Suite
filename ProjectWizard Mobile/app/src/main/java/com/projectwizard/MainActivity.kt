                }
            }
        }

        VerticalDivider(color = MaterialTheme.colorScheme.outline, modifier = Modifier.width(1.dp).fillMaxHeight())

        // Form fields center pane
        Column(
            modifier = Modifier
                .weight(1f)
                .fillMaxHeight()
                .padding(24.dp)
        ) {
            Text(
                text = "Create New Project",
                fontSize = 24.sp,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onSurface,
                modifier = Modifier.padding(bottom = 16.dp)
            )

            Box(modifier = Modifier.weight(1f)) {
                when (step) {
                    0 -> Column(verticalArrangement = Arrangement.spacedBy(16.dp)) {
                        Text("Configure your project basic identification properties.", color = MaterialTheme.colorScheme.onSurfaceVariant)
                        OutlinedTextField(
                            value = projectName,
                            onValueChange = { projectName = it },
                            label = { Text("Project Name") },
                            modifier = Modifier
                                .fillMaxWidth()
                                .testTag("wizard_proj_name"),
                            singleLine = true
                        )
                        OutlinedTextField(
                            value = group,
                            onValueChange = { group = it },
                            label = { Text("Group ID") },
                            modifier = Modifier.fillMaxWidth(),
                            singleLine = true
                        )
                        OutlinedTextField(
                            value = artifact,
                            onValueChange = { artifact = it },
                            label = { Text("Artifact ID") },
                            modifier = Modifier.fillMaxWidth(),
                            singleLine = true
                        )
                    }
                    1 -> Column(verticalArrangement = Arrangement.spacedBy(16.dp)) {
                        Text("Select your primary programming language.", color = MaterialTheme.colorScheme.onSurfaceVariant)
                        Row(horizontalArrangement = Arrangement.spacedBy(16.dp)) {
                            Card(
                                onClick = { language = "Java" },
                                modifier = Modifier
                                    .weight(1f)
                                    .height(100.dp),
                                border = BorderStroke(
                                    2.dp,
                                    if (language == "Java") MaterialTheme.colorScheme.primary else Color.Transparent
                                )
                            ) {
                                Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                                    Text("☕ Java", fontSize = 18.sp, fontWeight = FontWeight.Bold)
                                }
                            }
                            Card(
                                onClick = { language = "Kotlin" },
                                modifier = Modifier
                                    .weight(1f)
                                    .height(100.dp),
                                border = BorderStroke(
                                    2.dp,
                                    if (language == "Kotlin") MaterialTheme.colorScheme.primary else Color.Transparent
                                )
                            ) {
                                Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                                    Text("🎯 Kotlin", fontSize = 18.sp, fontWeight = FontWeight.Bold)
                                }
                            }
                        }
                    }
                    2 -> Column(verticalArrangement = Arrangement.spacedBy(16.dp)) {
                        Text("Choose the dependency management and build orchestrator.", color = MaterialTheme.colorScheme.onSurfaceVariant)
                        Row(horizontalArrangement = Arrangement.spacedBy(16.dp)) {
                            Card(
                                onClick = { buildTool = "Gradle" },
                                modifier = Modifier
                                    .weight(1f)
                                    .height(100.dp),
                                border = BorderStroke(
                                    2.dp,
                                    if (buildTool == "Gradle") MaterialTheme.colorScheme.primary else Color.Transparent
                                )
