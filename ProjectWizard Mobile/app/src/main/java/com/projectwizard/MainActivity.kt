                        label = { Text("Commit Message") },
                        modifier = Modifier.fillMaxWidth(),
                        enabled = gitService?.isGitRepository == true
                    )

                    Button(
                        onClick = {
                            if (commitMessage.isBlank()) {
                                gitStatusLog = "Error: Commit message cannot be empty!"
                            } else {
                                gitStatusLog = "[main 4c3df91] $commitMessage\n 1 file changed, 4 insertions(+), 1 deletion(-)"
                                commitMessage = ""
                            }
                        },
                        colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF4CAF50)),
                        enabled = gitService?.isGitRepository == true
                    ) {
                        Text("Git Commit")
                    }
                }
            }
        }

        Text("Console Log Output", fontWeight = FontWeight.Bold, fontSize = 14.sp)
        Card(
            modifier = Modifier
                .fillMaxWidth()
                .height(180.dp),
            colors = CardDefaults.cardColors(containerColor = Color.Black)
        ) {
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .verticalScroll(rememberScrollState())
                    .padding(12.dp)
            ) {
                Text(
                    text = gitStatusLog,
                    fontFamily = FontFamily.Monospace,
                    fontSize = 12.sp,
                    color = Color(0xFF4CAF50) // Green console text
                )
            }
        }
    }
}

