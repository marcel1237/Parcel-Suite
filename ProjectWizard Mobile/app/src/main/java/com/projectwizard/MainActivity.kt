// --- 4. PROJECT WORKSPACE TWO-PANE INTEGRATION ---
@Composable
fun ProjectWorkspaceScreen(
    project: GeneratedProject,
    persistenceService: PersistenceService,
    onCloseWorkspace: () -> Unit
) {
    // Keep track of opened file and expanded directories
    var openFile by remember { mutableStateOf<File?>(null) }
    var fileContent by remember { mutableStateOf("") }
    var editorModified by remember { mutableStateOf(false) }

    // Collage state for collapsed directories in PackageExplorer
    val expandedPaths = remember { mutableStateListOf<String>() }

    // Refresh tree trigger
    var treeRefreshKey by remember { mutableIntStateOf(0) }

    val context = LocalContext.current
    val projectDir = File(project.path)

    // Automatically load the project README.md on open or restore last file
    LaunchedEffect(project.path) {
        val openFiles: List<String> = persistenceService.getOpenFiles()
        val lastFile = if (openFiles.isNotEmpty()) File(openFiles[0]) else File(projectDir, "README.md")
        
        if (lastFile.exists() && lastFile.isFile) {
            openFile = lastFile
            fileContent = lastFile.readText()
            editorModified = false
        }
    }

    // Save open file to persistence
    LaunchedEffect(openFile) {
        val currentFile = openFile
        if (currentFile != null) {
            persistenceService.saveOpenFiles(listOf(currentFile.absolutePath))
        }
    }

    Row(modifier = Modifier.fillMaxSize()) {
        // Left column: Collapsible File Explorer tree (PackageExplorer)
        Column(
            modifier = Modifier
                .width(260.dp)
                .fillMaxHeight()
                .background(MaterialTheme.colorScheme.surface)
                .border(1.dp, MaterialTheme.colorScheme.outline, RoundedCornerShape(0.dp))
        ) {
            // Explorer Title
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(12.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                    Icon(Icons.Default.Folder, null, tint = MaterialTheme.colorScheme.primary, modifier = Modifier.size(16.dp))
                    Text("Package Explorer", fontWeight = FontWeight.Bold, fontSize = 14.sp)
                }
                IconButton(onClick = onCloseWorkspace) {
                    Icon(Icons.Default.Close, "Close project", modifier = Modifier.size(16.dp))
                }
            }

            HorizontalDivider(color = MaterialTheme.colorScheme.outline)

            // Real recursive file tree structure in LazyColumn
            key(treeRefreshKey) {
                LazyColumn(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(horizontal = 4.dp, vertical = 8.dp)
                ) {
                    item {
                        // Project root row
                        FileTreeRow(
                            file = projectDir,
                            indentation = 0,
                            isExpanded = expandedPaths.contains(projectDir.absolutePath),
                            onRowClicked = {
                                if (expandedPaths.contains(projectDir.absolutePath)) {
                                    expandedPaths.remove(projectDir.absolutePath)
                                } else {
                                    expandedPaths.add(projectDir.absolutePath)
                                }
                            }
                        )
                    }

                    // Children expansion
                    if (expandedPaths.contains(projectDir.absolutePath)) {
                        val itemsList = mutableListOf<Pair<File, Int>>()
                        val expandedSet = HashSet<String>()
                        for (path in expandedPaths) expandedSet.add(path)
                        buildFileTreeList(projectDir, 1, expandedSet, itemsList)

                        items(itemsList) { pair: Pair<File, Int> ->
                            val file = pair.first
                            val indent = pair.second
                            FileTreeRow(
                                file = file,
                                indentation = indent,
                                isExpanded = expandedPaths.contains(file.absolutePath),
                                onRowClicked = {
                                    if (file.isDirectory) {
                                        if (expandedPaths.contains(file.absolutePath)) {
                                            expandedPaths.remove(file.absolutePath)
                                        } else {
                                            expandedPaths.add(file.absolutePath)
                                        }
                                    } else {
                                        // Open text file
                                        try {
                                            openFile = file
                                            fileContent = file.readText()
                                            editorModified = false
                                        } catch (e: Exception) {
                                            Toast.makeText(context, "Cannot open: ${e.message}", Toast.LENGTH_SHORT).show()
                                        }
                                    }
                                }
                            )
                        }
                    }
                }
            }
        }

        VerticalDivider(color = MaterialTheme.colorScheme.outline, modifier = Modifier.width(1.dp).fillMaxHeight())

        // Right column: Code Editor (EditorPane)
        Column(
            modifier = Modifier
                .weight(1f)
                .fillMaxHeight()
                .background(MaterialTheme.colorScheme.background)
        ) {
            val activeFile = openFile
            if (activeFile != null) {
                // Editor File toolbar header
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .background(MaterialTheme.colorScheme.surfaceVariant)
                        .padding(horizontal = 16.dp, vertical = 8.dp),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column {
                        Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            Text(
                                text = activeFile.name,
                                fontWeight = FontWeight.Bold,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                            if (editorModified) {
                                Box(
                                    modifier = Modifier
                                        .size(6.dp)
                                        .clip(RoundedCornerShape(3.dp))
                                        .background(MaterialTheme.colorScheme.primary)
                                )
                            }
                        }
                        Text(
                            text = activeFile.parent ?: "",
                            fontSize = 11.sp,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }

                    // Save file button
                    Button(
                        onClick = {
                            try {
                                activeFile.writeText(fileContent)
                                editorModified = false
                                treeRefreshKey++
                                Toast.makeText(context, "File saved successfully!", Toast.LENGTH_SHORT).show()
                            } catch (e: Exception) {
                                Toast.makeText(context, "Save error: ${e.message}", Toast.LENGTH_SHORT).show()
                            }
                        },
                        colors = ButtonDefaults.buttonColors(containerColor = MaterialTheme.colorScheme.primary),
                        shape = RoundedCornerShape(6.dp),
                        contentPadding = PaddingValues(horizontal = 12.dp, vertical = 4.dp),
                        modifier = Modifier.testTag("editor_save_btn")
                    ) {
                        Icon(Icons.Default.Save, null, modifier = Modifier.size(16.dp))
                        Spacer(modifier = Modifier.width(4.dp))
                        Text("Save")
                    }
                }

                HorizontalDivider(color = MaterialTheme.colorScheme.outline)

                // Editable Code Canvas with Line Numbers and Syntax Highlighting
                Row(modifier = Modifier.fillMaxSize()) {
                    // Line numbers column
                    val lineCount = fileContent.split("\n").size
                    Column(
                        modifier = Modifier
                            .background(MaterialTheme.colorScheme.surface)
                            .padding(horizontal = 8.dp, vertical = 16.dp)
                            .fillMaxHeight(),
                        horizontalAlignment = Alignment.End
                    ) {
                        for (i in 1..lineCount) {
                            Text(
                                text = i.toString(),
                                style = MaterialTheme.typography.bodySmall.copy(
                                    fontFamily = FontFamily.Monospace,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.5f)
                                )
                            )
                        }
                    }

                    VerticalDivider(color = MaterialTheme.colorScheme.outline, modifier = Modifier.width(1.dp).fillMaxHeight())

                    // Raw text editor with formatted syntax highlighting overlay
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .fillMaxHeight()
                            .verticalScroll(rememberScrollState())
                            .horizontalScroll(rememberScrollState())
                            .padding(16.dp)
                    ) {
                        // Highlighting parser
                        val isDark = ThemeManager.currentTheme == ThemeType.PRIMER_DARK || 
                                     ThemeManager.currentTheme == ThemeType.DRACULA ||
                                     ThemeManager.currentTheme == ThemeType.NORD_DARK ||
                                     ThemeManager.currentTheme == ThemeType.CUPERTINO_DARK
                        val highlightedText = remember(fileContent, activeFile.name, isDark) {
                            SyntaxHighlighter.highlight(fileContent, activeFile.name, isDark)
                        }

                        // BasicTextField with VisualTransformation is an option, but for direct robust display,
                        // we can overlay a custom styled TextField or direct Editable text box
                        BasicTextField(
                            value = fileContent,
                            onValueChange = {
                                fileContent = it
                                editorModified = true
                            },
                            textStyle = MaterialTheme.typography.bodyMedium.copy(
                                fontFamily = FontFamily.Monospace,
                                color = MaterialTheme.colorScheme.onBackground
                            ),
                            modifier = Modifier
                                .fillMaxSize()
                                .testTag("code_editor_field"),
                            // Here we use Custom Visual Transformation to apply styling
                            visualTransformation = VisualTransformation { text ->
                                TransformedText(highlightedText, OffsetMapping.Identity)
                            }
                        )
                    }
                }
            } else {
                Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                    Text("Select a file from the explorer to open in the code editor.", color = MaterialTheme.colorScheme.onSurfaceVariant)
                }
            }
        }
    }
}

// Utility function to recursive list directories for collapse explorer
fun buildFileTreeList(dir: File, indent: Int, expandedPaths: Set<String>, list: MutableList<Pair<File, Int>>) {
    val files = dir.listFiles() ?: return
    // Sort directories first, then files
    files.sortWith(compareBy({ !it.isDirectory }, { it.name.lowercase() }))

    for (file in files) {
        list.add(Pair(file, indent))
        if (file.isDirectory && expandedPaths.contains(file.absolutePath)) {
            buildFileTreeList(file, indent + 1, expandedPaths, list)
        }
    }
}


