@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AppShell() {
    val context = LocalContext.current
    val persistenceService = remember { PersistenceService(context) }
    var currentScreen by remember { mutableStateOf(Screen.HOME) }
    var selectedProject by remember { mutableStateOf<GeneratedProject?>(null) }
    var selectedTemplateForWizard by remember { mutableStateOf<ProjectTemplate?>(null) }

    // Dynamic state of loaded projects in the workspace
    var projectList by remember { mutableStateOf(WorkspaceManager.listProjects(context)) }

    // Restore last opened project
    LaunchedEffect(Unit) {
        val savedTheme = persistenceService.theme
        if (savedTheme != null) {
            try {
                ThemeManager.currentTheme = ThemeType.valueOf(savedTheme)
            } catch (e: Exception) {}
        }

        val lastPath = persistenceService.lastProjectPath as? String
        if (lastPath != null) {
            val file = File(lastPath)
            if (file.exists() && file.isDirectory) {
                val projects: List<GeneratedProject> = WorkspaceManager.listProjects(context)
                var found: GeneratedProject? = null
                for (proj in projects) {
                    if (proj.path == file.absolutePath) {
                        found = proj
                        break
                    }
                }
                if (found != null) {
                    selectedProject = found
                    currentScreen = Screen.WORKSPACE
                }
            }
        }
    }

    // Edge-to-edge window insets padding
    val windowInsets = WindowInsets.systemBars

    // Sidebar navigation action helper
    val navigateTo: (Screen) -> Unit = { target ->
        currentScreen = target
    }

    // Callback when a project is generated by the Wizard
    val onProjectCreated: (String, String, String, String, String) -> Unit = { name, group, artifact, lang, build ->
        val dir = WorkspaceManager.createProject(context, name, group, artifact, lang, build)
        projectList = WorkspaceManager.listProjects(context)
        selectedProject = GeneratedProject(
            name = dir.name,
            path = dir.absolutePath,
            language = lang,
            buildTool = build,
            group = group
        )
        persistenceService.saveLastProjectPath(dir.absolutePath)
        currentScreen = Screen.WORKSPACE
        Toast.makeText(context, "Project '$name' created!", Toast.LENGTH_SHORT).show()
    }

    BoxWithConstraints(
        modifier = Modifier
            .fillMaxSize()
            .windowInsetsPadding(windowInsets)
    ) {
        val isWide = this.maxWidth > 720.dp

        Row(modifier = Modifier.fillMaxSize()) {
            // Left sidebar for Expanded screens, or simple icon-rail
            if (isWide) {
                SidebarRail(
                    currentScreen = currentScreen,
                    onNavigate = { target: Screen ->
                        navigateTo(target)
                    },
                    modifier = Modifier
                        .width(240.dp)
                        .fillMaxHeight()
                        .background(MaterialTheme.colorScheme.surface)
                        .border(1.dp, MaterialTheme.colorScheme.outline, RoundedCornerShape(0.dp))
                )
            }

                // Main application column (Title Bar, Body Workspace, Status Bar)
                Column(modifier = Modifier.weight(1f)) {
                    // Top Action Menu Bar
                TopMenuBar(
                    currentScreen = currentScreen,
                    onNavigate = navigateTo,
                    onExit = { /* Simulated Exit */ }
                )

                HorizontalDivider(color = MaterialTheme.colorScheme.outline, thickness = 1.dp)

                // Main body area (Workspace)
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth()
                ) {
                    when (currentScreen) {
                        Screen.HOME -> DashboardScreen(
                            onNewProject = {
                                selectedTemplateForWizard = null
                                navigateTo(Screen.NEW_PROJECT)
                            },
                            onOpenProject = {
                                navigateTo(Screen.OPEN_PROJECT)
                            }
                        )
                        Screen.NEW_PROJECT -> NewProjectWizardScreen(
                            initialTemplate = selectedTemplateForWizard,
                            onCancel = { navigateTo(Screen.HOME) },
                            onFinish = onProjectCreated
                        )
                        Screen.OPEN_PROJECT -> OpenProjectScreen(
                            projects = projectList,
                            onProjectSelected = { proj ->
                                selectedProject = proj
                                persistenceService.saveLastProjectPath(proj.path)
                                navigateTo(Screen.WORKSPACE)
                            },
                            onDeleteProject = { proj ->
                                val dir = File(proj.path)
                                if (dir.exists()) {
                                    dir.deleteRecursively()
                                }
                                projectList = WorkspaceManager.listProjects(context)
                                Toast.makeText(context, "Deleted project ${proj.name}", Toast.LENGTH_SHORT).show()
                            }
                        )
                        Screen.TEMPLATES -> TemplatesScreen(
                            onSelectTemplate = { temp ->
                                selectedTemplateForWizard = temp
                                navigateTo(Screen.NEW_PROJECT)
                            }
                        )
                        Screen.GIT -> GitScreen(selectedProject)
                        Screen.GITHUB -> GitHubScreen()
                        Screen.SETTINGS -> SettingsScreen(persistenceService)
                        Screen.ABOUT -> AboutScreen()
                        Screen.WORKSPACE -> {
                            val activeProj = selectedProject
                            if (activeProj != null) {
                                ProjectWorkspaceScreen(
                                    project = activeProj,
                                    persistenceService = persistenceService,
                                    onCloseWorkspace = {
                                        selectedProject = null
                                        persistenceService.saveLastProjectPath("")
                                        navigateTo(Screen.OPEN_PROJECT)
                                    }
                                )
                            } else {
                                navigateTo(Screen.OPEN_PROJECT)
                            }
                        }
                    }
                }

                HorizontalDivider(color = MaterialTheme.colorScheme.outline, thickness = 1.dp)

                // IDE Bottom Status bar
                BottomStatusBar(
                    currentScreen = currentScreen,
                    activeProject = selectedProject
                )
            }
        }

        // Bottom Navigation Bar for narrow screens (portrait phones)
        if (!isWide) {
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .align(Alignment.BottomCenter)
                    .background(MaterialTheme.colorScheme.surface)
            ) {
                // Since edge-to-edge system navigation might collide, we render a highly compact navigation row
                // overlay only if absolutely needed, but standard practice is a elegant bottom bar.
                // Let's implement it inside the layout rather than overlay to avoid covering content.
            }
        }
    }
}

